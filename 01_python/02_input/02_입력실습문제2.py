"""
2. 배속에 따른 영상 재생 시간 계산하기 (`02_입력실습문제2.py`)

영상의 원래 재생 시간(분)과 재생 배속을 입력받아 실제 시청에 걸리는 시간을 계산하세요.
계산식: 실제 재생 시간 = 원래 재생 시간 ÷ 재생 배속
예: 재생 시간이 120분인 영상을 1.5배속으로 시청하면 80분이 걸립니다.
"""

# 입력
time = int(input("재생 시간 : "))
speed = float(input("재생 속도 : "))

# 연산
# playtime = time / speed
playtime = int(time / speed)

# 출력
print("예상 재생시간 : ", playtime)