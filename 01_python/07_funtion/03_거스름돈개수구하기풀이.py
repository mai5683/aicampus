"""
함수 실습 : 잔액과 거스름돈 개수 구하기
상품 금액과 지불한 금액을 이용해서 다음과 같은 영수증을 출력하는 함수를 만드세요

<구매 영수증>
-------------------
상품 가격 : 55750원
지불 금액 : 60000원
-------------------
거스름돈 : 4250원
 +-- 1000원짜리 4장
 +-- 100원짜리 2개
 +-- 50원짜리 1개


5만원짜리부터 개수를 검사하며, 줄 필요 없는 금액에 대해서는 출력하지 않습니다.
"""


# 프로그램을 함수 없이 시작하면 바로 결과가 나오게 구현

# 입력
price = 55750
pay = 60000

# 연산
change = pay-price
copy = change  # change가 변하지 않게 하기 위해 복사
count50000 = copy // 50000  # 50000원권 개수 구하기
copy %= 50000
count10000 = copy // 10000  # 10000원권 개수 구하기
copy %= 10000
count5000 = copy // 5000  # 5000원권 개수 구하기
copy %= 5000
count1000 = copy // 1000  # 1000원권 개수 구하기
copy %= 1000
count500 = copy // 500  # 500원권 개수 구하기
copy %= 500
count100 = copy // 100  # 100원권 개수 구하기
copy %= 100
count50 = copy // 50  # 50원권 개수 구하기
copy %= 50
count10 = copy // 10  # 10원권 개수 구하기
copy %= 10

# 출력
print("<영수증>")
print(f"상품 가격 : {price}원")
print(f"지불 금액 : {pay}원")
print("-"*20)
print(f"거스름돈 : {change}원")
print(f"  +-- 50000원짜리 {count50000}개")
print(f"  +-- 10000원짜리 {count10000}개")
print(f"  +-- 5000원짜리 {count5000}개")
print(f"  +-- 1000원짜리 {count1000}개")
print(f"  +-- 500원짜리 {count500}개")
print(f"  +-- 100원짜리 {count100}개")
print(f"  +-- 50원짜리 {count50}개")
print(f"  +-- 10원짜리 {count10}개")
