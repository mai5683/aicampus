"""
# 실습 문제 : 생년월일 검사하기

파일명 : `04_생년월일검사.py`

- 1단계 : `0000-00-00`부터 `9999-99-99`까지 가능하게 만들기
- 2단계 : `1900-01-01`부터 `2099-12-31`까지 가능하게 만들기
  - (2-1) 모든 달을 `31`일까지 있다고 가정하고 식 생성
  - (2-2) 작은달과 큰달, 2월을 구분하여 식 생성 (2월은 29일까지 있다고 가정)
"""

import re

birth = "2000-05-31"
# regexp = r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$"
# regexp = r"^(19[0-9]{2}|20[0-9]{2})-(0[1-9]|1[0-2])-(0[1-9]|1[0-9]|2[0-9]|3[01])$"
regexp = r"^(19[0-9]{2}|20[0-9]{2})-((02-(0[1-9]|1[0-9]|2[0-9]))|((0[469]|11)-(0[1-9]|1[0-9]|2[0-9]|30))|((0[13578]|1[02])-(0[1-9]|1[0-9]|2[0-9]|3[01])))$"
result = re.fullmatch(regexp, birth)

if result is not None:
    print("올바른 생년월일 입니다")
else:
    print("잘못된 생년월일 입니다")