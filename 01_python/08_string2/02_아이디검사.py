"""
실습 과제 : 올바른 아이디 검사하기
파일명 : 02_아이디검사.py

사용자에게 아이디를 입력받아 다음과 같이 검사 후 출력하세요

검사규칙
- 시작은 반드시 영문 소문자로 할것
- 영문 소문자 또는 숫자 5~20글자의 범위 내에서 작성할 것
- 그 외 다른 글자는 불가

결과
아이디가 형식에 일치하면 멋진 아이디네요! 출력
아이디가 형식에 일치하지 않으면 아이디는 영문 소문자로 시작하고 숫자를 포함해 5~20글자로 작성하세요 출력
"""

import re

# id = "testuser123"
id = input("ID : ")

regexp = r"^[a-z][a-z0-9]{4,19}$"
# regexp = "^[a-z][a-z0-9\\-\\_]{4,19}$"
# regexp = r"^[a-z][a-z0-9\-\_]{4,19}$"

result = re.match(regexp, id)  # 정규표현식으로 id를 검사하라

if result is not None:
    print("멋진 아이디네요!")
else :
    print("아이디는 영문 소문자로 시작하고 숫자를 포함해 5~2글자로 작성하세요")
