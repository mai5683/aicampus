# 회원가입 프로그램 (중반부 어딘가쯤을 구현)

database = {
    # "ID" : "Password"
    "testuser1" : "testuser1!",
    "testuser2" : "testuser2!",
    "testuser3" : "testuser3!",
    "testuser4" : "testuser4!"
}

# 사용자 입력
id = input("아이디 입력 : ")
pw = input("비밀번호 입력 : ")

if id in database:
    print("이미 사용 중인 아이디입니다.")
else:
    database[id] = pw   # 실제 등록 코드
    print("회원가입이 완료되었습니다.")







