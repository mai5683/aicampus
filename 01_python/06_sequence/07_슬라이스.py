"""
# 슬라이싱

리스트를 원하는 구간으로 잘라내는 것을 말함.
위치를 이용하여 잘라냄.
[ 시작 : 종료 : 간격 ] 과 같이 표시
"""


names = ["피카츄", "라이츄", "파이리", "꼬부기", "버터플"]

print(names)
print(names[1])  # 라이츄(슬라이싱 X)
print(names[1:3])  # 1 초과부터 3 미만까지 (range와 같은 형태)
print(names[0:3])  # 앞에서 3개
print(names[:3])  # 앞에서 3개
print(names[1:])  # 1 초과부터 끝까지 (0: 으로 시작한다면 1부터 출력)

# (Q) 뒤에서 3개만
print(names[-3:])

# 한 칸씩 띄고 자르기
print(names[::2])  # [::3] 이면 두 칸씩 띄고 자르기

# 역순으로 가져오기
print(names[::-1])  # [::1] 이면 원래 순서대로 출력되는데 - 가 붙어서 왼쪽 방향으로 출력되는 개념

