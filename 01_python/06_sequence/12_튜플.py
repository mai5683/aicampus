"""
튜플(tuple)

리스트(list)처럼 데이터를 순차적으로 보관하는 저장소
(이후 등장하는 함수 등에서 내부적으로 사용됨)

단, 튜플은 오직 읽기(Read)만 가능하다.
"""

# 생성 방법이 다르다
li = [10, 20, 30, 40, 50]
tu = (10, 20, 30, 40, 50)

print(li[0], li[1], li[-1])
print(tu[0], tu[1], tu[-1])

li[2] = 100  # 수정
print(li)

# tu[2] = 100
# print(tu)

# tu.append(), tu.remove(), del, tu[2] = 100 등이 모두 금지
# list와 같은 작업보단 프로그래밍 내부적인 처리에 사용

# 다음과 같이 쓰면 a에 10이, b에 20이 들어간다.
(a,b) = (10, 20)
c,d = 30, 40
print(a, b, c, d)

# a, b에 저장된 값을 서로 교체(swap) 해보세요.
a,b = b,a
print(a, b)

e = (10 + 20)  # 이건 튜플이 아님.  e = (10 + 20, ) 이런 식이어야 튜플임.
print(e)


