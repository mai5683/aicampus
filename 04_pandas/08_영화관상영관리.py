# 3. 전체 영화의 잔여좌석 합계
print(f"전체 잔여좌석 개수는 {df["잔여좌석"].sum()}개입니다.")

# 4. 잔여좌석이 가장 적은 영화의 잔여좌석 수
print(f"가장 적은 잔여좌석 수는 {df["잔여좌석"].min()}개입니다.")

