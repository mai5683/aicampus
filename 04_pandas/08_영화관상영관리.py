"""
# Pandas 실습 문제 — 영화관 상영 관리
영화관에서 상영작별 좌석 수와 예매 현황을 관리하고 있습니다.
다음 데이터를 이용하여 영화관 관리자의 요청을 처리하세요.

## 제한사항
- 반복문과 `if` 조건문은 사용하지 마세요.
- `loc`, 조건 필터링, `drop()` 및 기존에 배운 Pandas 통계 함수를 활용하세요.
- `groupby()`, `sort_values()` 등 아직 배우지 않은 함수는 사용하지 마세요.
"""

## 기본 데이터

import pandas as pd

df = pd.DataFrame({
    "장르": ["액션", "애니메이션", "코미디", "SF", "드라마"],
    "전체좌석": [100, 80, 60, 120, 70],
    "예매좌석": [75, 60, 25, 110, 50],
    "관람료": [15000, 12000, 13000, 16000, 14000]
}, index=["영화A", "영화B", "영화C", "영화D", "영화E"])

print(df, "\n")


## 요구사항

# **1. 예매 현황 수정**
# 영화A에서 10명의 관객이 추가로 예매했습니다.
# 영화A의 예매좌석을 기존보다 10 증가시키세요.
df.loc["영화A", "예매좌석"] += 10
print(df, "\n")

# (고민해 볼 내용) 예매좌석의 상한 하한을 맞춰서 clip 처리
# numpy : np.clip(배열, 하한선, 상한선)
# pandas : df.clip(하한선, 상한선)

# (ex) 전체좌석 수를 0~100 사이로 제한
# df["전체좌석"] = df["전체좌석"].clip(0, 100)
# print(df, "\n")

# (Q) 예매좌석에 상한 하한을 적용해 clip 처리 해보세요.
df["예매좌석"] = df["예매좌석"].clip(0, df["전체좌석"])
print(df, "\n")

# **2. 관람료 인상**
# 주말 요금 정책으로 모든 영화의 관람료를 2,000원씩 인상하세요.
df["관람료"] += 2000
df["관람료"] = df["관람료"].clip(lower=0)
print(df, "\n")

# **3. 새로운 영화 등록**
# 다음 영화를 DataFrame에 추가하세요.
# - 영화명: 영화F
# - 장르: 공포
# - 전체좌석: 90
# - 예매좌석: 30
# - 관람료: 15,000원
# ※ 영화F는 주말 요금 인상이 이미 반영된 가격으로 등록합니다.
df.loc["영화F"] = ["공포", 90, 30, 15000]
print(df, "\n")

# **4. 상영 종료 처리**
# 영화C의 상영이 종료되었습니다.
# 영화C에 해당하는 행을 삭제하세요.
df = df.drop(index="영화C")
print(df, "\n")

# **5. 남은 좌석 계산**
# 각 영화의 남은 좌석을 계산하여 `잔여좌석`이라는 새로운 열에 저장하세요.
# 계산식: 전체좌석 - 예매좌석
df["잔여좌석"] = df["전체좌석"] - df["예매좌석"]
print(df, "\n")

# **6. 매진 임박 영화 확인**
# 잔여좌석이 15석 이하인 영화의 정보를 모두 출력하세요.
condition = df["잔여좌석"] <= 15
print(df.loc[condition], "\n")

# (Q) 잔여좌석이 10% 이하인 영화의 정보를 모두 출력하세요.
# condition = df["잔여좌석"] / df["전체좌석"] <= 0.1
condition = df["잔여좌석"] <= df["전체좌석"] * 0.1
print(df.loc[condition], "\n")


# **7. 예매 수입 계산**
# 각 영화의 `관람료 × 예매좌석`을 계산하여 `예매수입` 열을 추가하세요.
df["예매수입"] = df["관람료"] * df["예매좌석"]
print(df, "\n")

# **8. 불필요한 정보 제거**
# 영화별 예매수입을 확인한 뒤 `장르` 열을 삭제하세요.
df = df.drop(columns="장르")
print(df, "\n")


