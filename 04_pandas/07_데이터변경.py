"""
DataFrame에 담긴 데이터를 변경하는 작업

- 변경에 해당하는 작업 : C(create), U(update), D(delete)
"""

import pandas as pd

df = pd.DataFrame(
        {
        "분류" : ["음료", "과자", "음료", "식품"],
        "가격" : [2000, 1500, 1800, 4500],
        "재고" : [15, 3, 20, 8],
        "판매량" : [30, 45, 50, 12]
    },
    index = ["콜라", "새우깡", "생수", "도시락"]
)

print(df, "\n")


# ------------------------------------------
# 수정
# ------------------------------------------

# 탐색은 셋 중 하나 : df[컬럼] or df.loc[행, 열] or df.iloc[행, 열]
# (Q) 새우깡 재고를 10개로 변경
df.loc["새우깡", "재고"] = 10
print(df,"\n")

# (Q) 콜라의 가격을 2500원으로 변경
df.loc["콜라", "가격"] = 2500
# df.loc["콜라"]["가격"] = 2500   # error
print(df,"\n")

# (Q) 모든 상품의 가격을 300원 증가
df["가격"] += 300
# df.loc[:, "가격"] += 300
print(df,"\n")

# (Q) 콜라의 정보를 ["음료", 1500, 5, 50] 으로 변경?
# print(df.loc["콜라"])
df.loc["콜라"] = ["음료", 1500, 5, 50]
print(df,"\n")


# ------------------------------------------
# 추가
# ------------------------------------------

# 새로운 상품(초코우유) 등록
# (없는 상품의 전체정보 수정과 같음)
df.loc["초코우유"] = ["음료", 2000, 15, 0]
print(df,"\n")

# (Q) 홈런볼 (과자, 2500원, 20개, 판매량 0) 추가
df.loc["홈런볼"] = ["과자", 2500, 20, 0]
print(df,"\n")

# 새로운 항목(열) 추가
# (Q) 가격과 판매량을 이용해서 판매누적액 항목 신설
df["판매누적액"] = df["가격"] * df["판매량"]
df["매장"] = "1호점"
print(df,"\n")

# (Q) 데이터가 모자르더라도 추가가 될까? (불가능)
# df.loc["컵라면"] = ["라면", 2000, 10, 0]
# print(df,"\n")


# ------------------------------------------
# 행 또는 열 제거
# ------------------------------------------
# - (중요) 삭제는 원본을 변경하지 않음. (사본 생성)
# - 원본을 지우고 싶다면 (1) 덮어쓰거나, (2) inplace 옵션을 부여
# inplace=True → 앞으로 못 쓸 예정 (비추천)

# 초코우유 삭제
df = df.drop(index="초코우유")
print(df,"\n")

# (Q) 매장 항목을 삭제
df = df.drop(columns="매장")
print(df,"\n")

