# **9. 긴급 발주 대상 선정**
# 매장에서는 다음 조건을 모두 만족하는 상품을 긴급 발주하기로 했습니다.
# - 판매량이 30개 이상
# - 현재 재고가 5개 미만
# 긴급 발주가 필요한 상품들의 재고와 판매량만 출력하고, 해당 상품이 몇 종류인지 계산하세요.
condition = (df["판매량"] >= 30) & (df["재고"] < 5)
print(df.loc[condition, ["재고", "판매량"]])
print("판매 가능한 종류 :", len(df.loc[condition]))



