"""
# 실습 문제 (06_데이터프레임조건실습.py)

# Pandas 종합 실습 — 편의점 재고 관리
편의점에서 판매하는 상품의 가격, 재고, 판매량을 관리하고 있습니다.
매장 관리자의 요청에 따라 필요한 데이터를 분석하는 프로그램을 작성하세요.
---

### 제한사항

- `for`, `while` 반복문을 사용하지 마세요.
- `if` 조건문을 사용하지 마세요.
- Pandas의 `loc`, `iloc`, 조건 필터링, `mean()`, `len()` 등을 활용하세요.
- 아직 배우지 않은 `groupby()`, `sort_values()` 등은 사용하지 않아도 됩니다.
"""

## 기본 데이터

import pandas as pd

df = pd.DataFrame({
    "분류": ["음료", "과자", "음료", "식품", "과자", "음료", "식품", "과자"],
    "가격": [2000, 1500, 3500, 4500, 2500, 1800, 6000, 1200],
    "재고": [15, 3, 0, 8, 2, 20, 1, 12],
    "판매량": [30, 45, 25, 12, 38, 50, 10, 60]
}, index=[
    "콜라", "새우깡", "에너지드링크", "도시락",
    "초코파이", "생수", "샌드위치", "껌"
])

print(df)
print()


# ## 요구사항

# **1. 품절 상품 확인**
# 손님이 구매할 수 없는 상품을 확인하려고 합니다.
# 현재 재고가 없는 상품의 모든 정보를 출력하세요.
condition = df["재고"] == 0
print(df.loc[condition, :], "\n")

# **2. 재고 부족 상품 확인**
# 재고가 5개 미만인 상품들을 찾아 상품명, 가격, 재고만 출력하세요.
condition = df["재고"] < 5
print(df.loc[condition, ("가격","재고")], "\n")

# **3. 음료 판매 현황**
# 음료에 해당하는 상품들의 가격과 판매량만 출력하세요.
print(df.loc[df["분류"] == "음료", ["가격", "판매량"]], "\n")

# **4. 저렴한 상품 추천**
# 손님이 2,000원 이하의 상품을 찾고 있습니다.
# 현재 구매 가능한 상품 중 가격이 2,000원 이하인 상품을 모두 출력하세요.
condition = (df["가격"] <= 2000) & (df["재고"] > 0)
print(df.loc[condition].index, "\n")

# **5. 인기 상품 확인**
# 판매량이 40개 이상이면서 현재 재고가 남아 있는 상품을 출력하세요.
condition = (df["판매량"] >= 40) & (df["재고"] > 0)
print(df.loc[condition].index, "\n")

# **6. 고가 상품 재고 확인**
# 가격이 3,000원 이상이거나 재고가 2개 이하인 상품을 모두 출력하세요.
condition = (df["가격"] >= 3000) | (df["재고"] <= 2)
print(df.loc[condition].index, "\n")

# **7. 재고 관리 보고서**
# 현재 판매 가능한 상품이 몇 종류인지 출력하고, 해당 상품들의 평균 가격을 계산하세요.
condition = df["재고"] > 0
print("판매 가능한 종류 :", len(df.loc[condition]))
print("평균 가격 :", df.loc[condition, "가격"].mean(), "\n")

# **8. 특정 위치의 데이터 조회**
# 상품의 이름을 사용하지 않고 숫자 위치만 이용하세요.
# - 세 번째 상품의 모든 정보 출력
# - 마지막 상품의 가격 출력
# - 두 번째부터 다섯 번째 상품까지의 가격과 재고 출력
print(df.iloc[2])
print(df.iloc[-1] ["가격"])
print(df.iloc[1:5][["가격", "재고"]], "\n")

# ## 추가 도전 문제
