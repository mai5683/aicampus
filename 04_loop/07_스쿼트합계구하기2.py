"""
오늘부터 다이어트를 위해 한달간 스쿼트를 하려고 합니다.
처음부터 많이하긴 어려우니까 다음과 같은 목표를 설정했습니다.

첫 날은 자세를 신경쓰며 10개만 합니다.
둘째 날부터는 전날보다 4개 더 많이 합니다.

1. 제가 한달 동안 매일같이 하게되는 스쿼트는 각각 몇개씩인지 출력하세요
2. 한달동안 한 총 스쿼트 개수는 몇개인지 출력하세요.
3. 사용자에게 기간을 입력받아서 해당 기간만큼 진행할 수 있도록 변경해보세요.
"""

squat = 10  # 매일 할 스쿼트 횟수
total = 0  # 총 스쿼트 누적 횟수

# 계획기간(일)
period = int(input("며칠 하실 건가요? : "))

for day in range(1,period+1) :
    print(f"{day}일차 : {squat}개")
    total += squat
    # print("총 갯수 :", total,"개")  # 확인용
    squat += 4

print("총 횟수 : ", total,"개")
