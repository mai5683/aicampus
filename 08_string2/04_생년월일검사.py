"""
실습 문제 : 생년월일 검사하기
1단계 : 0000-00-00부터 9999-99-99까지 가능하게 만들기
2단계 : 1900-01-01부터 2099-12-31까지 가능하게 만들기
(2-1) 모든 달을 31일까지 있다고 가정하고 식 생성
(2-2) 작은달과 큰달, 2월을 구분하여 식 생성 (2월은 29일까지 있다고 가정)
"""

import re

birth = input("생년월일 : ")

regexp1 = r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$"
result1 = re.match(regexp1, birth)

regexp2 = r"^[1,2][9,0][0-9]{2}-[0,1][0-9]-[0,3][0,9]$"
result2 = re.match(regexp2, birth)