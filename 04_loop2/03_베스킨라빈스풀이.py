"""
다음 규칙에 맞는 베스킨라빈스 게임을 구현하세요

사용자 두 명이 하나의 컴퓨터에서 하는 게임입니다.
사용자는 1 ~ 3 사이의 숫자만 입력이 가능합니다.
입력이 잘못된 경우 다시 입력을 받습니다.
숫자는 1부터 시작합니다.
사용자가 입력한 숫자만큼 숫자를 선택합니다.
사용자가 1을 입력하면 1개의 숫자를 선택한다는 의미입니다. (1)
사용자가 2을 입력하면 2개의 숫자를 선택한다는 의미입니다. (1, 2)
사용자가 3을 입력하면 3개의 숫자를 선택한다는 의미입니다. (1, 2, 3)

31을 선택하는 사람이 지는 게임입니다.

베스킨 라빈스 게임 시작!
[현재 : 1] 숫자 1~3개 선택 : (1)
[현재 : 2] 숫자 1~3개 선택 : (2)
[현재 : 4] 숫자 1~3개 선택 : (3)
[현재 : 7] 숫자 1~3개 선택 : ...
...(중간 생략)...
[현재 : 29] 숫자 1~3개 선택 : (2)
[현재 : 31] 숫자 1~3개 선택 : (1)
31을 선택하여 게임이 종료되었습니다.

* 다 하면 컴퓨터는 랜덤으로 1~3을 고르게 해서 번갈아 진행
"""


now = 1

while True :
    text = f"[ 현재 : {now} ] 숫자 1~3개 선택 : "
    choice = int(input(text))

    # 1~3이 아닌 경우를 스킵 처리
    # if choice < 1 or choice > 3 :
    #     continue
    if not (choice >= 1 and choice <= 3) :
        continue

    # now 부터 now+choice 전까지 반복하며 출력
    for i in range(now, now + choice) :
        print(f"→ {i} 선택")

    now += choice

    # 나가는 시점 처리
    if now > 31 :
        break

print("31을 선택하여 게임이 종료되었습니다.")
