"""
파일 입출력(File I/O) : 프로그램의 데이터를 파일로 내보내거나 파일에서 불러오는 것

- 파일출력 : 프로그램에서 파일로 데이터를 내보내는 것 (저장)
- 파일입력 : 파일에서 프로그램으로 데이터를 불러오는 것 (열기)

* 파일에 저장된 건 결국 글자이며, 해석할 수 있냐 없냐의 차이만 존재
"""

# 대상 파일을 점유(선택)
# file = open("파일명", "모드", encoding="글꼴")
# w(write), r(read), a(append)
file = open("hello.txt", "w", encoding="utf-8")  # 글꼴은 utf-8로 통합되고 있음

# 내용을 작성해서 내보내기
file.write("hello python!\n")
file.write("안녕하세요\n")
file.write("파이썬 파일 출력 테스트 중입니다")

# 파일에 대한 점유 해제 (안 하면 다른 프로그램에서 해당 파일을 사용할 수 없음. 메모리 누수 발생.)
file.close()
