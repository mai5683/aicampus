"""
실습 과제 : 욕설 필터링 프로그램

다음 규칙에 맞는 욕설 필터링 프로그램을 만드세요

사용자에게 채팅 한 줄을 입력받습니다.
입력된 채팅에 욕설이 존재하는지 확인합니다.
만약 욕설이 존재할 경우 그 욕설과 동일한 글자수의 *로 치환합니다.
(ex) 이런 신발끈 개나리 수박씨를 보았나 → 이런 *** *** ***를 보았나

욕설 단어 예시

신발끈, 시베리아, 수박씨, 개나리, 십장생, 십자수, 조카, 주옥

그 외 자유롭게 추가
"""

# 입력
line = input("입력 : ")
# line = "이런 신발끈 같은 상황이 있나..."

# 연산(필터링)
filter = ["신발끈", "시베리아", "수박씨", "개나리", "십장생", "십자수", "조카", "주옥"]

for word in filter :
    mask = "*" * len(word)
    line = line.replace(word, mask)
# 출력
print("결과 :", line)