"""
[문제: 편의점 거스름돈 계산하기]

편의점에서 여러 명의 손님이 물건을 구매하고 있습니다.
다음 조건에 맞게 거스름돈을 계산하는 프로그램을 작성하세요.

[문제 조건]

1. 손님이 몇 명인지 입력받습니다.
2. 손님 수만큼 반복하면서 구매 금액과 지불한 금액을 입력받습니다.
3. 지불한 금액이 구매 금액보다 적으면 "받은 금액이 부족합니다."를 출력하고 거스름돈은 0원으로 처리합니다.
4. 지불한 금액이 충분하면 거스름돈을 계산합니다.
5. 거스름돈을 1,000원 단위로 나누어 1,000원권 개수와 남은 금액을 출력합니다.
6. 모든 손님의 거스름돈을 합산하여 마지막에 출력합니다.

[실행 예시]

몇 명이 방문하나요? : 4

구매 금액 : 6500
받은 금액 : 10000
거스름돈 : 3500원
1000원권 : 3장
남은 금액 : 500원

구매 금액 : 12000
받은 금액 : 20000
거스름돈 : 8000원
1000원권 : 8장
남은 금액 : 0원

구매 금액 : 4500
받은 금액 : 5000
거스름돈 : 500원
1000원권 : 0장
남은 금액 : 500원

구매 금액 : 8000
받은 금액 : 5000
받은 금액이 부족합니다.
거스름돈 : 0원
1000원권 : 0장
남은 금액 : 0원

총 거스름돈 : 12000원

[사용할 개념]
- for 반복문
- if / else 조건문
- input()
- int()
- f-string
- // 몫 연산자
- % 나머지 연산자
- total을 이용한 누적 합계
"""


person = int(input("몇 명이 방문하나요? : "))

print()

total = 0

for i in range(person) :
    buy = int(input("구매 금액 : "))
    paid = int(input("받은 금액 : "))

    if paid < buy :
        print("받은 금액이 부족합니다.")
        change = 0
    else :
        change = paid - buy

    one_thousand_won = change // 1000
    won = change % 1000

    print(f"거스름돈 : {change}원")
    print(f"1000원권 : {one_thousand_won}장")
    print(f"남은 금액 : {won}원")

    total += change

print()

print(f"총 거스름돈 : {total}원")

