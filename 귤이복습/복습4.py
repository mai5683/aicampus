"""
좋아! 😄 이번에는 지금까지 배운 `random`, `for`, `if/else`, 변수, 점수 계산을 활용하는 문제를 만들어볼게.

지난번 구구단 게임과 비슷한 난이도지만, 소재를 바꿔봤어.

# 🏃 파이썬 연습 문제: 숫자 맞히기 게임

난이도: 초급 ~ 초중급

문제 설명

컴퓨터가 1부터 10까지의 숫자 중 하나를 무작위로 선택해.

사용자는 정해진 횟수만큼 숫자를 입력해서 컴퓨터가 선택한 숫자를 맞혀야 해.

구현 조건

1. 사용자에게 게임을 몇 번 진행할지 입력받는다.
2. 컴퓨터가 1~10 사이의 숫자를 무작위로 선택한다.
3. 사용자가 숫자를 입력한다.
4. 입력한 숫자가 정답이면 `정답입니다!`를 출력하고 점수 10점을 추가한다.
5. 입력한 숫자가 정답보다 작으면 `UP!`을 출력한다.
6. 입력한 숫자가 정답보다 크면 `DOWN!`을 출력한다.
7. 오답이면 점수 5점을 차감한다.
8. 점수가 0점보다 낮아지면 0점으로 만든다.
9. 정답과 오답 횟수, 최종 점수를 출력한다.

추가 도전 조건

- 정답을 연속으로 맞히면 콤보가 증가한다.
- 첫 번째 연속 정답은 10점, 두 번째는 20점, 세 번째는 30점을 추가한다.
- 오답을 입력하면 콤보는 0으로 초기화된다.

## 실행 예시

```
게임을 몇 번 진행하시겠습니까? : 4

숫자 입력 : 3
UP!

숫자 입력 : 7
정답입니다!

숫자 입력 : 5
UP!

숫자 입력 : 7
정답입니다!

<게임 결과>
정답 횟수 : 2회
오답 횟수 : 2회
최종 점수 : 15점

게임을 종료합니다.
```

위 실행 예시는 기본 점수 방식이 아닌 콤보 추가 조건까지 적용한 예시야.

### 💡 힌트

처음부터 추가 도전 조건까지 한꺼번에 구현하지 않아도 돼.

1. 먼저 기본 조건 1~9번을 완성해 봐.
2. 그다음 콤보 점수 기능을 추가해 봐.

정답 코드는 미리 알려주지 않을게! 네가 작성한 코드를 보내주면 지난번처럼 틀린 부분을 하나씩 짚어줄게. 😊
"""

import random

correct = 0
wrong = 0
question = int(input("문제를 몇 번 풀겠습니까? : "))

score = 0
combo = 0

for i in range(question) :
    answer = random.randint(1, 10)
    user = int(input("숫자 입력 : "))
    if answer > user :
        print("UP!")
        wrong += 1
        score -= 5
        combo = 0
    elif answer < user :
        print("DOWN!")
        wrong += 1
        score -= 5
        combo = 0
    else :
        print("정답입니다!")
        correct += 1
        combo += 1
        score += 10 * combo

    if score < 0 :
        score = 0

print()

print("<게임 결과>")
print(f"정답 횟수 : {correct} 회")
print(f"오답 횟수 : {wrong} 회")
print(f"최종 점수 : {score} 점")
print()
print("게임을 종료합니다.")