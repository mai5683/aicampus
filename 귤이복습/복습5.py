"""
## 이번 연습 문제: 영화관 입장료 계산기

초급 · 새로운 개념 1개

문제 설명

영화관에서 손님들의 나이를 입력받아 총 입장료를 계산하는 프로그램을 만들어 봐.

입장료 규칙은 다음과 같아.

- 12세 이하: 7,000원
- 13세 이상 64세 이하: 12,000원
- 65세 이상: 7,000원

프로그램 조건

1. 손님이 몇 명인지 입력받는다.
2. 입력받은 손님 수만큼 반복한다.
3. 손님 한 명씩 나이를 입력받는다.
4. 나이에 따라 입장료를 계산한다.
5. 모든 손님의 입장료를 합산한다.
6. 마지막에 총 입장료를 출력한다.

출력 예시

```
몇 명이 방문하나요? : 3

1번째 손님 나이 : 10
입장료 : 7000원

2번째 손님 나이 : 25
입장료 : 12000원

3번째 손님 나이 : 70
입장료 : 7000원

총 입장료 : 26000원
```

### 이번에 새롭게 배울 코드

`or`라는 연산자를 하나만 추가해 보자.

```
if age <= 12 or age >= 65:
```

`or`는 양쪽 조건 중 하나라도 참이면 실행한다는 뜻이야.

즉, 12세 이하이거나 65세 이상이면 할인 요금을 적용하는 거지.

### 힌트

- 손님 수를 입력받는 코드는 반복문 바깥에!
- 나이를 입력받는 코드는 반복문 안에!
- 총 입장료를 저장할 변수는 반복문 전에 `0`으로 설정해 봐.
- 손님마다 입장료를 계산한 다음 총액에 더하면 돼.
"""


guest = int(input("몇 명이 방문하나요? : "))
total = 0

for i in range(guest) :
    age = int(input("손님 나이 : "))
    if age <= 12 or age >= 65 :
        charge = 7000
        total += charge
        print(f"입장료 : {charge}원")
    else :
        charge = 12000
        total += charge
        print(f"입장료 : {charge}원")

print()

print(f"총 입장료 : {total}원")
