"""
[문제: 게임 레벨 계산하기]

여러 명의 플레이어가 게임을 하고 있습니다.

각 플레이어의 점수를 입력받아 레벨과 남은 포인트를 계산하는 프로그램을 작성하세요.

[문제 조건]

1. 플레이어가 몇 명인지 입력받습니다.
2. 플레이어 수만큼 반복하면서 각 플레이어의 게임 점수를 입력받습니다.
3. 게임 점수 100점마다 레벨이 1씩 올라갑니다.
4. 레벨과 다음 레벨까지 남은 포인트를 출력합니다.
5. 레벨이 3 이상이면 "목표 레벨을 달성했습니다."를 출력합니다.
6. 레벨이 3 미만이면 "조금 더 노력하세요!"를 출력합니다.
7. 모든 플레이어의 점수를 합산합니다.
8. 마지막에 전체 점수를 레벨과 남은 포인트로 변환하여 출력합니다.

[실행 예시]

몇 명의 플레이어가 있나요? : 3

게임 점수 : 250
현재 레벨 : 2레벨
남은 포인트 : 50점
조금 더 노력하세요!

게임 점수 : 380
현재 레벨 : 3레벨
남은 포인트 : 80점
목표 레벨을 달성했습니다.

게임 점수 : 90
현재 레벨 : 0레벨
남은 포인트 : 90점
조금 더 노력하세요!

전체 점수 : 720점
전체 레벨 : 7레벨
남은 포인트 : 20점

[사용할 개념]
- for 반복문
- if / else 조건문
- input()
- int()
- f-string
- // 몫 연산자
- % 나머지 연산자
- total을 이용한 누적 합계
"""


player = int(input("몇 명의 플레이어가 있나요? : "))

total = 0

print()

for i in range(player) :
    score = int(input("게임 점수 : "))
    level = score // 100
    remain_point = score % 100

    print(f"현재 레벨 : {level}레벨")
    print(f"남은 포인트 : {remain_point}점")

    if level < 3 :
        print("조금 더 노력하세요!")

    else :
        print("목표 레벨을 달성했습니다.")

    print()

    total += score

total_level = total // 100
total_remain_point = total % 100

print(f"전체 점수 : {total}점")
print(f"전체 레벨 : {total_level}레벨")
print(f"남은 포인트 : {total_remain_point}점")