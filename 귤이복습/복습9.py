"""
[문제: 자전거 주행 거리 계산하기]

자전거를 탄 사람들의 주행 거리를 입력받아 기록하는 프로그램을 작성하세요.

[문제 조건]

1. 자전거를 탄 사람이 몇 명인지 입력받습니다.
2. 사람 수만큼 반복하면서 각 사람의 주행 거리(미터)를 입력받습니다.
3. 자전거 트랙은 한 바퀴에 400m입니다.
4. 각 사람의 완주한 바퀴 수와 남은 거리를 출력합니다.
5. 완주한 바퀴가 5바퀴 이상이면 "5바퀴 이상 완주했습니다."를 출력합니다.
6. 5바퀴 미만이면 "5바퀴 미만 주행했습니다."를 출력합니다.
7. 모든 사람의 주행 거리를 합산합니다.
8. 마지막에 전체 주행 거리를 km와 m로 변환하여 출력합니다.

[실행 예시]

몇 명이 자전거를 탔나요? : 3

주행 거리(m) : 1800
완주 바퀴 : 4바퀴
남은 거리 : 200m
5바퀴 미만 주행했습니다.

주행 거리(m) : 2300
완주 바퀴 : 5바퀴
남은 거리 : 300m
5바퀴 이상 완주했습니다.

주행 거리(m) : 900
완주 바퀴 : 2바퀴
남은 거리 : 100m
5바퀴 미만 주행했습니다.

전체 주행 거리 : 5km 0m

[사용할 개념]
- for 반복문
- if / else 조건문
- // 몫 연산자
- % 나머지 연산자
- total을 이용한 누적 합계
"""

person = int(input("몇 명이 자전거를 탔나요? : "))

print()

total = 0

for i in range(person) :
    mileage = int(input("주행 거리(m) : "))
    turn = mileage // 400
    remain = mileage % 400
    print(f"완주 바퀴 : {turn}바퀴")
    print(f"남은 거리 : {remain}m")

    if turn < 5 :
        print("5바퀴 미만 주행했습니다.")
    else :
        print("5바퀴 이상 주행했습니다.")

    total += mileage

total_km = total // 1000
total_m = total % 1000

print()

print(f"전체 주행 거리 : {total_km}km {total_m}m")