"""
[문제: 운동 시간 계산 프로그램]

여러 사람의 운동 시간을 입력받아 운동 시간을 계산하는 프로그램을 작성하세요.

[문제 조건]

1. 운동한 사람이 몇 명인지 입력받습니다.
2. 사람 수만큼 반복하면서 각 사람의 운동 시간(분)을 입력받습니다.
3. 운동 시간을 시간과 분으로 변환하여 출력합니다.
4. 운동 시간이 60분 이상이면 "1시간 이상 운동했습니다."를 출력합니다.
5. 운동 시간이 60분 미만이면 "1시간 미만 운동했습니다."를 출력합니다.
6. 모든 사람의 운동 시간을 합산합니다.
7. 마지막에 전체 운동 시간을 시간과 분으로 변환하여 출력합니다.

[실행 예시]

몇 명이 운동했나요? : 3

운동 시간(분) : 45
운동 시간 : 0시간 45분
1시간 미만 운동했습니다.

운동 시간(분) : 80
운동 시간 : 1시간 20분
1시간 이상 운동했습니다.

운동 시간(분) : 125
운동 시간 : 2시간 5분
1시간 이상 운동했습니다.

전체 운동 시간 : 4시간 10분

[사용할 개념]
- for 반복문
- if / else 조건문
- // 몫 연산자
- % 나머지 연산자
- total을 이용한 누적 합계
"""

person = int(input("몇 명이 운동했나요? : "))

print()

total = 0

for i in range(person) :
    time = int(input("운동 시간(분) : "))
    hour = int(time / 60)
    minute = int(time % 60)
    print(f"운동 시간 : {hour}시간 {minute}분")
    if time < 60 :
        print("1시간 미만 운동했습니다.")
    else :
        print("1시간 이상 운동했습니다.")

    total += time

print()

total_hour = int(total / 60)
total_minute = int(total % 60)
print(f"전체 운동 시간 : {total_hour}시간 {total_minute}분")
