"""
직접 생성한 컬러 이미지를 흑백으로 변환한 뒤,
컬러 이미지와 흑백 이미지를 가로로 나란히 합쳐 출력하는 프로그램을 작성하세요.

추가로 합성한 이미지의 밝기를 증가시킨 결과도 만들어 비교하세요.

* 1단계 — 컬러 이미지 생성
np.zeros()를 이용해 (300, 450, 3) 크기의 컬러 이미지를 만듭니다.
이미지를 가로 150픽셀씩 세 구역으로 나눕니다.
각 구역의 색상은 다음과 같습니다.

     너비 450px / 높이 : 300px
┌──────────┬──────────┬──────────┐
│          │          │          │
│  파란색   │  초록색   │  빨간색   │
│          │          │          │
└──────────┴──────────┴──────────┘
   150px      150px      150px

⚠️ OpenCV의 BGR 순서를 사용하세요.

* 2단계 — 흑백 이미지 변환
1. 생성한 컬러 이미지를 cv2.cvtColor()로 흑백 변환합니다.
2. 흑백 이미지의 shape를 출력합니다.
3. np.stack()으로 흑백 이미지를 3채널로 변환합니다.
4. 변환한 이미지의 shape도 출력합니다.

* 3단계 — 이미지 크기 변경
1. 컬러 이미지의 높이를 150px로 변경합니다.
2. 흑백 3채널 이미지도 높이를 150px로 변경합니다.
3. 두 이미지 모두 원래의 가로세로비가 유지되도록 너비를 계산하세요.
4. cv2.resize()를 이용해 변경합니다.

* 4단계 — 이미지 합성
1. np.hstack()으로 두 이미지를 합칩니다.
2. 왼쪽에는 컬러 이미지, 오른쪽에는 흑백 이미지가 나오게 합니다.
3. 합성한 이미지의 shape를 출력합니다.

*  5단계 — 밝기 조절
1. 합성 이미지를 .copy()로 복사합니다.
2. 복사한 이미지의 전체 밝기를 30 증가시킵니다.
3. np.clip()으로 밝기를 0~255 범위로 제한합니다.
4. 결과를 np.uint8로 변환합니다.

* 6단계 — 이미지 출력
cv2.imshow()로 다음 두 이미지를 각각 출력합니다.
- original : 컬러 + 흑백 합성 이미지
- bright : 합성 후 밝기를 30 증가시킨 이미지
"""