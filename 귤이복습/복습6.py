"""
## 📝 문제: 편의점 구매 금액 계산하기

편의점에서 손님들이 물건을 구매하고 있어.
다음 조건에 맞게 프로그램을 작성해 봐!

문제 조건

1. 손님이 몇 명인지 입력받는다.
2. 손님 수만큼 반복하면서 각 손님이 구매한 금액을 입력받는다.
3. 구매 금액이 30,000원 이상이면 10% 할인해 준다.
4. 30,000원 미만이면 할인 없이 원래 금액을 받는다.
5. 각 손님이 실제로 결제할 금액을 출력한다.
6. 모든 손님의 결제 금액을 합산해서 마지막에 출력한다.

### 실행 예시

```
몇 명이 방문하나요? : 3

구매 금액 : 20000
결제 금액 : 20000원

구매 금액 : 40000
결제 금액 : 36000원

구매 금액 : 50000
결제 금액 : 45000원

총 결제 금액 : 101000원
```

### 힌트 💡

- `guest` : 방문한 손님 수
- `total` : 전체 결제 금액
- `price` : 손님이 구매한 원래 금액
- `charge` : 할인 적용 후 실제 결제 금액

이번에는 `price`와 `charge`를 구분해서 사용해 보는 게 핵심이야!
"""

guest = int(input("몇 명이 방문하나요? : "))

print()

rate = 0
total = 0

for i in range(guest) :
    price = int(input("구매금액 : "))

    if price < 30000 :
        rate = 0

    else :
        rate = 10

    discount = int(price * rate / 100)
    charge = price - discount
    total += charge

    print(f"구매금액 : {price}원")
    print(f"결제금액 : {charge}원")



print()

print(f"총 결제금액 : {total}원")