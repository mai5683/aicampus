"""
실습 문제 : 인기 투표 프로그램
인기가요 등 가요 프로그램에서 1위후보에게 투표하듯이 좋아하는 연예인의 이름을 적으면 해당 연예인에게 투표가 되는 프로그램을 구현하세요

이미 존재하는 이름인 경우 득표수를 1 증가시킵니다.
처음 등록하는 이름인 경우 득표수를 1로 설정합니다.
종료를 입력하면 해당 키워드는 등록하지 않고 투표를 종료합니다.

<인기 투표 프로그램>
투표할 연예인 이름 입력 : (피카츄)
→ 피카츄 투표가 완료되었습니다 (현재 : 1표)
투표할 연예인 이름 입력 : (라이츄)
→ 라이츄 투표가 완료되었습니다 (현재 : 1표)
투표할 연예인 이름 입력 : (라이츄)
→ 라이츄 투표가 완료되었습니다 (현재 : 2표)
투표할 연예인 이름 입력 : (피카츄)
→ 피카츄 투표가 완료되었습니다 (현재 : 2표)
투표할 연예인 이름 입력 : (피카츄)
→ 피카츄 투표가 완료되었습니다 (현재 : 3표)
투표할 연예인 이름 입력 : (종료)
** 투표가 종료되었습니다 **

가능하다면 검색을 통해 투표 종료 후 투표현황을 출력해보세요.
"""

singer = {}

singer["피카츄"] = 0
singer["라이츄"] = 0

while True:
    print("<인기 투표 프로그램>")
    user = input("투표할 연예인 이름 입력 : ")
    if user in singer:
        singer[user] += 1
        print(f"→ 피카츄 투표가 완료되었습니다 (현재 : {singer[user]}표)")
    else:
        singer[user] += 1
        print(f"→ 라이츄 투표가 완료되었습니다 (현재 : {singer[user]}표)")

    if "종료" == singer:
        print("** 투표가 종료되었습니다 **")
        break
